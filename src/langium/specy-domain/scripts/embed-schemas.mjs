// Embeds the JSON Schemas of the model documents (src/schemas/*.schema.json at
// the root of specy-skill) into src/formats/generated/schemas.ts, so the CLI
// and the browser bundle validate a JSON or YAML document without reading the
// disk. The schema files stay the source of truth; this runs before tsc and
// before the tests.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemasDir = resolve(root, '../../schemas');
const outDir = resolve(root, 'src/formats/generated');
mkdirSync(outDir, { recursive: true });

// file name -> language key of the registry
const LANGUAGE_OF = {
    'domain-model.schema.json': 'domain',
    'prd.schema.json': 'prd',
    'sysreq.schema.json': 'sysreq',
    'architecture.schema.json': 'architecture',
    'synth-scenario.schema.json': 'synth',
};

const entries = [];
for (const file of readdirSync(schemasDir).sort()) {
    const language = LANGUAGE_OF[file];
    if (!language) continue;
    const schema = JSON.parse(readFileSync(resolve(schemasDir, file), 'utf8'));
    entries.push(`    ${language}: ${JSON.stringify(schema, null, 4).replace(/\n/g, '\n    ')},`);
}

writeFileSync(
    resolve(outDir, 'schemas.ts'),
    `/* Generated by scripts/embed-schemas.mjs from src/schemas/*.schema.json — do not edit. */\n` +
        `export const SCHEMAS: Record<string, Record<string, unknown>> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`embedded ${entries.length} schema(s) into src/formats/generated/schemas.ts`);
