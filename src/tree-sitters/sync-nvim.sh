#!/usr/bin/env bash
set -euo pipefail

# =============================================================================
# Sync Neovim with the Specy tree-sitter parsers
#
# Writes <nvim-config>/plugin/specy-tree-sitter.lua, generated from every
# parser in src/tree-sitters/: its file extensions (from tree-sitter.json), its
# compiled library and its highlight queries. Re-run it after adding, renaming
# or moving a parser — the file is regenerated from scratch. Rebuilding an
# existing parser needs no re-run: the file points at this checkout.
#
# It also removes the "-- [specy-tree-sitter]" block that the former
# install-nvim.sh appended to init.lua (backing init.lua up first), then opens
# each file type in a headless Neovim, with your config, to check that it is
# highlighted.
#
# Requires: Neovim 0.10+, parsers built (./src/tree-sitters/build.sh).
#
# Usage: ./src/tree-sitters/sync-nvim.sh
#        NVIM_APPNAME=<name> ./src/tree-sitters/sync-nvim.sh   # another config
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

MARKER="-- [specy-tree-sitter]"
END_MARKER="-- [/specy-tree-sitter]"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[0;33m'; BOLD='\033[1m'; RESET='\033[0m'

die() { printf "${RED}ERROR:${RESET} %s\n" "$1" >&2; exit 1; }

# lua_quote <text> — a single-quoted Lua string literal
lua_quote() { printf "'%s'" "$(printf '%s' "$1" | sed -e "s/[\\\\']/\\\\&/g")"; }

# ---------------------------------------------------------------------------
# Pre-flight checks
# ---------------------------------------------------------------------------

command -v nvim >/dev/null 2>&1 || die "nvim not on PATH."

# The config directory of the Neovim on PATH (honours NVIM_APPNAME and XDG_CONFIG_HOME).
nvim_info=$(nvim --headless --clean \
  -c 'lua io.stdout:write(vim.fn.stdpath("config"), "\n", vim.fn.has("nvim-0.10"), "\n")' \
  -c 'qa!' 2>/dev/null) || die "could not run nvim."
NVIM_DIR=$(printf '%s\n' "$nvim_info" | sed -n 1p)
[[ "$(printf '%s\n' "$nvim_info" | sed -n 2p)" == 1 ]] || die "Neovim 0.10+ required."
PLUGIN_FILE="$NVIM_DIR/plugin/specy-tree-sitter.lua"
INIT_LUA="$NVIM_DIR/init.lua"

lib_ext="so"
[[ "$(uname)" == "Darwin" ]] && lib_ext="dylib"

work_dir=$(mktemp -d "${TMPDIR:-/tmp}/specy-nvim-sync.XXXXXX")
trap 'rm -rf "$work_dir"' EXIT

# ---------------------------------------------------------------------------
# Collect the parsers
# ---------------------------------------------------------------------------

rows=""         # Lua table rows, one per parser
languages=""    # Lua list of the parser languages (= filetypes)
extensions=""   # every file extension, for the check below
missing=0

for dir in "$SCRIPT_DIR"/tree-sitter-specy-*; do
  json="$dir/tree-sitter.json"
  [[ -f "$json" ]] || continue
  name=$(basename "$dir")

  # The first "name" in tree-sitter.json is the grammar's — the language Neovim knows it by.
  lang=$(grep -m1 -oE '"name"[[:space:]]*:[[:space:]]*"[^"]+"' "$json" | sed -E 's/.*"([^"]+)"$/\1/')
  exts=$(tr -d '\n' < "$json" | sed -nE 's/.*"file-types"[[:space:]]*:[[:space:]]*\[([^]]*)\].*/\1/p' | tr -d ' \t"')
  [[ -n "$lang" && -n "$exts" ]] || die "$name/tree-sitter.json: no grammar name or file-types."

  # `tree-sitter build` names the library after the directory: specy-domain.dylib.
  lib="$dir/${name#tree-sitter-}.$lib_ext"
  if [[ ! -f "$lib" ]]; then
    printf "${RED}ERROR:${RESET} %s not built (%s not found)\n" "$name" "$(basename "$lib")" >&2
    missing=1
    continue
  fi

  # Neovim looks for highlights in queries/<lang>/ on the runtimepath.
  if [[ -f "$dir/queries/highlights.scm" && ! -e "$dir/queries/$lang/highlights.scm" ]]; then
    mkdir -p "$dir/queries/$lang"
    ln -s ../highlights.scm "$dir/queries/$lang/highlights.scm"
    printf "${YELLOW}Created${RESET} %s/queries/%s/highlights.scm -> ../highlights.scm\n" "$name" "$lang"
  fi

  ext_list=""
  for ext in ${exts//,/ }; do
    ext_list+="$(lua_quote "$ext"), "
    extensions+="$ext "
  done
  rows+="  { lang = $(lua_quote "$lang"), extensions = { ${ext_list%, } }, dir = $(lua_quote "$dir"), lib = $(lua_quote "$lib") },"$'\n'
  languages+="$(lua_quote "$lang"), "
done

[[ $missing -eq 1 ]] && die "run ./src/tree-sitters/build.sh first."
[[ -n "$rows" ]] || die "no parser found in $SCRIPT_DIR."
rows=${rows%$'\n'}

# ---------------------------------------------------------------------------
# Write the plugin file
# ---------------------------------------------------------------------------

cat > "$work_dir/plugin.lua" << LUAEOF
-- Specy tree-sitter highlighting.
-- Generated by $SCRIPT_DIR/sync-nvim.sh — do not edit:
-- re-run that script after adding, renaming or moving a parser. Delete this file to uninstall.

local parsers = {
$rows
}

for _, p in ipairs(parsers) do
  -- Skipped while the checkout is out of reach (moved, or an unmounted drive).
  if vim.uv.fs_stat(p.lib) then
    for _, ext in ipairs(p.extensions) do
      vim.filetype.add({ extension = { [ext] = p.lang } })
    end
    vim.treesitter.language.add(p.lang, { path = p.lib })
    -- for queries/<lang>/highlights.scm
    vim.opt.runtimepath:append(p.dir)
  end
end

vim.api.nvim_create_autocmd('FileType', {
  pattern = { ${languages%, } },
  callback = function(ev)
    vim.treesitter.start(ev.buf, ev.match)
  end,
})
LUAEOF

mkdir -p "$(dirname "$PLUGIN_FILE")"
if cmp -s "$work_dir/plugin.lua" "$PLUGIN_FILE"; then
  echo "$PLUGIN_FILE already in sync."
else
  cat "$work_dir/plugin.lua" > "$PLUGIN_FILE"
  echo "Wrote $PLUGIN_FILE"
fi

# ---------------------------------------------------------------------------
# Remove the block the former install-nvim.sh appended to init.lua
# ---------------------------------------------------------------------------

if [[ -f "$INIT_LUA" ]] && grep -qF -- "$MARKER" "$INIT_LUA"; then
  backup="$INIT_LUA.bak-$(date +%Y%m%d-%H%M%S)"
  cp -p "$INIT_LUA" "$backup"
  cleaned=$(awk -v start="$MARKER" -v end="$END_MARKER" '
    { line = $0; sub(/[ \t]+$/, "", line) }
    line == start { skip = 1; next }
    skip { if (line == end) skip = 0; next }
    line == "" { blanks++; next }           # blank lines are kept only before a non-blank one
    { for (; blanks > 0; blanks--) print ""; print }
  ' "$INIT_LUA")
  # Written in place, so an init.lua symlinked from a dotfiles repo stays a symlink.
  printf '%s\n' "$cleaned" > "$INIT_LUA"
  echo "Removed the old $MARKER block from $INIT_LUA (backup: $(basename "$backup"))"
fi

# ---------------------------------------------------------------------------
# Check: open one file per extension with the user's config
# ---------------------------------------------------------------------------

probe_files=""
for ext in $extensions; do
  : > "$work_dir/probe.$ext"
  probe_files+="$work_dir/probe.$ext"$'\n'
done

cat > "$work_dir/probe.lua" << 'LUAEOF'
local results = {}
for _, path in ipairs(vim.split(vim.env.SPECY_PROBE_FILES, '\n', { trimempty = true })) do
  vim.cmd.edit(vim.fn.fnameescape(path))
  local buf = vim.api.nvim_get_current_buf()
  local ft = vim.bo[buf].filetype
  local status
  if ft == '' then
    status = 'no filetype'
  elseif not vim.treesitter.highlighter.active[buf] then
    status = 'filetype ' .. ft .. ', but tree-sitter highlighting not started'
  else
    local ok, query = pcall(vim.treesitter.query.get, ft, 'highlights')
    if not ok then
      status = 'highlights query error: ' .. (tostring(query):gsub('\n', ' '))
    elseif not query then
      status = 'filetype ' .. ft .. ', but no highlights query found'
    else
      status = 'ok ' .. ft
    end
  end
  table.insert(results, 'PROBE\t.' .. vim.fn.fnamemodify(path, ':e') .. '\t' .. status)
end
io.stdout:write(table.concat(results, '\n') .. '\n')
LUAEOF

echo ""
printf "${BOLD}Checking with your Neovim config${RESET}\n"
probe_output=$(SPECY_PROBE_FILES="$probe_files" nvim --headless \
  -c "luafile $work_dir/probe.lua" -c 'qa!' 2>&1 || true)

fail=0
for ext in $extensions; do
  status=$(printf '%s\n' "$probe_output" | awk -F'\t' -v ext=".$ext" '$1 == "PROBE" && $2 == ext { print $3 }')
  case "$status" in
    ok\ *) printf "  ${GREEN}%-10s OK${RESET} (%s)\n" ".$ext" "${status#ok }" ;;
    "")    printf "  ${RED}%-10s FAILED${RESET} (Neovim did not report)\n" ".$ext"; fail=1 ;;
    *)     printf "  ${RED}%-10s FAILED${RESET} (%s)\n" ".$ext" "$status"; fail=1 ;;
  esac
done

if [[ $fail -eq 1 ]]; then
  echo ""
  echo "Neovim output:"
  printf '%s\n' "$probe_output" | grep -v '^PROBE' | sed 's/^/  /'
  exit 1
fi

echo ""
echo "Restart any running Neovim to pick the change up."
